function detectInitialLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && SUPPORTED_LANGS.includes(saved)) return saved;
  } catch (e) {
    /* localStorage unavailable -- fall through to the browser language */
  }
  const preferred = (navigator.languages || [navigator.language || ""]).map((l) =>
    String(l).toLowerCase().slice(0, 2)
  );
  for (const code of preferred) {
    if (SUPPORTED_LANGS.includes(code)) return code;
  }
  return DEFAULT_LANG;
}

let currentLang = detectInitialLang();
const pluralRulesCache = {};

function pluralCategory(count) {
  if (!pluralRulesCache[currentLang]) {
    pluralRulesCache[currentLang] = new Intl.PluralRules(currentLang);
  }
  return pluralRulesCache[currentLang].select(count);
}

function t(key, params = {}) {
  let value = TRANSLATIONS[currentLang][key];
  if (value === undefined) value = TRANSLATIONS.en[key];
  if (value === undefined) return key;
  if (value && typeof value === "object" && !Array.isArray(value)) {
    const category = pluralCategory(Number(params.count ?? 0));
    value = value[category] ?? value.other ?? Object.values(value)[0];
  }
  if (typeof value !== "string") return value;
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    params[name] !== undefined ? String(params[name]) : match
  );
}

function formatPercent(value) {
  return new Intl.NumberFormat(currentLang, { style: "percent", maximumFractionDigits: 0 }).format(
    value
  );
}

function applyStaticTranslations() {
  document.documentElement.lang = LANG_TAGS[currentLang] || currentLang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  currentLang = lang;
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang);
  } catch (e) {
    /* ignore -- per-viewer convenience only */
  }
  applyStaticTranslations();
  const select = document.getElementById("lang-select");
  if (select) select.value = lang;
  if (typeof window.onLanguageChange === "function") {
    window.onLanguageChange(lang);
  }
}

function initLanguageSwitcher(selectEl) {
  selectEl.innerHTML = "";
  for (const code of SUPPORTED_LANGS) {
    const opt = document.createElement("option");
    opt.value = code;
    opt.textContent = LANG_NAMES[code];
    opt.lang = LANG_TAGS[code] || code;
    selectEl.appendChild(opt);
  }
  selectEl.value = currentLang;
  selectEl.addEventListener("change", () => setLang(selectEl.value));
  applyStaticTranslations();
}
